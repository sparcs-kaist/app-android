internal const val THEME_GENERATOR_KEY = "theme-generator"

private const val EDITOR_ROUTE = "TimetableThemeEditor"
private const val GENERATOR_ROUTE = "TimetableThemeGenerator"
private const val IMPORT_ROUTE = "TimetableThemeImport"
private const val SHARING_ROUTE = "TimetableThemeSharing"
private const val SEED_ARGUMENT = "seed"
private const val CODE_ARGUMENT = "code"
private const val THEME_ARGUMENT = "theme"

// Keys on the editor's SavedStateHandle: the draft the generator starts from, and its result.
private const val GENERATOR_BASE_KEY = "generatorBase"
private const val GENERATED_THEME_KEY = "generatedTheme"

fun NavController.navigateToThemeEditor(theme: TimetableTheme) {
    navigate("$EDITOR_ROUTE?$SEED_ARGUMENT=${Uri.encode(Json.encodeToString(theme))}")
}

fun NavController.navigateToThemeImport(code: String) {
    navigate("$IMPORT_ROUTE?$CODE_ARGUMENT=${Uri.encode(code)}")
}

fun NavController.navigateToThemeSharing(theme: TimetableTheme) {
    navigate("$SHARING_ROUTE?$THEME_ARGUMENT=${Uri.encode(Json.encodeToString(theme))}")
}

/**
 * Theme list, editor, AI generator, import and sharing as separate destinations, so each gets
 * predictive back.
 */
fun NavGraphBuilder.timetableThemeGraph(navController: NavController) {
    composable(Channel.TimetableThemeSettings.name) {
        TimetableThemeSettingsView(navController)
    }

    composable(
        route = "$EDITOR_ROUTE?$SEED_ARGUMENT={$SEED_ARGUMENT}",
        arguments = listOf(navArgument(SEED_ARGUMENT) { type = NavType.StringType })
    ) { entry ->
        val seed = entry.arguments?.getString(SEED_ARGUMENT) ?: return@composable
        val store = rememberTimetableThemeStore()
        val generated by entry.savedStateHandle
            .getStateFlow<String?>(GENERATED_THEME_KEY, null)
            .collectAsState()
        TimetableThemeEditor(
            seed = seed,
            onBack = { navController.popBackStack() },
            onSave = store::saveAndSelect,
            onOpenGenerator = { draft ->
                entry.savedStateHandle[GENERATOR_BASE_KEY] = Json.encodeToString(draft)
                navController.navigate(GENERATOR_ROUTE)
            },
            generatedTheme = remember(generated) {
                generated?.let { Json.decodeFromString<TimetableTheme>(it) }
            },
            onGeneratedThemeConsumed = { entry.savedStateHandle[GENERATED_THEME_KEY] = null }
        )
    }

    composable(
        route = "$IMPORT_ROUTE?$CODE_ARGUMENT={$CODE_ARGUMENT}",
        arguments = listOf(navArgument(CODE_ARGUMENT) { type = NavType.StringType })
    ) { entry ->
        val code = entry.arguments?.getString(CODE_ARGUMENT) ?: return@composable
        val store = rememberTimetableThemeStore()
        TimetableThemeImportRoute(
            initialCode = code,
            onClose = { navController.popBackStack() },
            onImport = { theme ->
                store.saveAndSelect(theme)
                navController.popBackStack()
            }
        )
    }

    composable(
        route = "$SHARING_ROUTE?$THEME_ARGUMENT={$THEME_ARGUMENT}",
        arguments = listOf(navArgument(THEME_ARGUMENT) { type = NavType.StringType })
    ) { entry ->
        val theme = remember(entry) {
            entry.arguments?.getString(THEME_ARGUMENT)?.let { Json.decodeFromString<TimetableTheme>(it) }
        } ?: return@composable
        TimetableThemeSharingRoute(
            theme = theme,
            onClose = { navController.popBackStack() },
            navController = navController
        )
    }

    composable(GENERATOR_ROUTE) { entry ->
        val editorEntry = remember(entry) { navController.previousBackStackEntry } ?: return@composable
        val baseTheme = remember(editorEntry) {
            editorEntry.savedStateHandle.get<String>(GENERATOR_BASE_KEY)
                ?.let { Json.decodeFromString<TimetableTheme>(it) }
        } ?: return@composable
        ThemeGeneratorDestination(navController, editorEntry, baseTheme)
    }
}

@Composable
private fun ThemeGeneratorDestination(
    navController: NavController,
    editorEntry: NavBackStackEntry,
    baseTheme: TimetableTheme,
) {
    val generator: TimetableThemeGeneratorViewModel =
        viewModel(viewModelStoreOwner = editorEntry, key = THEME_GENERATOR_KEY)
    val state by generator.state.collectAsState()
    // Keep the description when the user backs out; the editor resets it after applying.
    ThemeGeneratorLifecycleEffect(generator, resetOnDispose = false)
    OnPoppedEffect(navController) { generator.cancel() }

    TimetableThemeGeneratorView(
        state = state,
        baseTheme = baseTheme,
        onDescriptionChange = generator::describe,
        onGenerate = { generator.generate(baseTheme, it) },
        onDownload = generator::download,
        onRefresh = generator::refreshAvailability,
        onCancel = generator::cancel,
        onBack = { navController.popBackStack() },
        onApply = { theme ->
            editorEntry.savedStateHandle[GENERATED_THEME_KEY] = Json.encodeToString(theme)
            navController.popBackStack()
        },
    )
}
